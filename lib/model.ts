// Token Radar model, version radar-2 ("peer-anchored").
//
// The board ranks every pre-token protocol the snapshot can rank: the
// watchlist is the floor, never the ceiling, and the early radar is every
// other rankable protocol below (and above) that floor. A protocol is
// rankable when the snapshot records no token for it and it is not a
// wrapped, staked or bridged product, not an exchange, and not a versioned
// pool of another protocol -- the same exclusions the house watchlist rule
// states, applied without the TVL floor. Live-token protocols are never
// ranked: they are set aside with the market cap the market already gave
// them, and they are also the model's price anchor.
//
// Implied value follows only from the snapshot's own figures:
//
//   peerMultiple  = shrunk median of (mcap_usd / tvl_usd) over the
//                   live-token protocols of the same category,
//                   pulled toward the global median when the category
//                   has few live peers, clamped to [0.08, 0.90].
//                   Each live ratio is first winsorized to [0.02, 1.0]:
//                   a thin protocol whose token trades far above its
//                   TVL must not set its whole category's price.
//                   A category nobody prices yet falls back to the
//                   global median, never to a hand-picked number.
//   growthMult    = 1 + clamp(change_7d, -60, 120) / 100 * 0.6
//   maturityMult  = 0.55 + 0.45 * (1 - exp(-age_days / 548))
//                   Age is days since first listing: how long the
//                   protocol has run with no token. Unknown age uses the
//                   median age of its category, else 365 days.
//   chainMult     = 1 + 0.02 * min(chains - 1, 4), at most 1.08:
//                   a protocol live on more chains is harder to kill.
//   implied       = max(1, round(tvl_usd * peerMultiple
//                                 * growthMult * maturityMult * chainMult))
//
// No protocol name is ever special-cased: the same function scores every
// row, and the dashboard recomputes each row from these figures and checks
// the number board.json carries.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
